-- T-11: catálogo de provincias y localidades de Argentina, para elegir la ubicación del barrio de una lista
-- normalizada en lugar de escribirla a mano. Datos oficiales de Georef (apis.datos.gob.ar/georef, descargados el
-- 6/11/2026): 24 provincias y 3931 localidades. Los id son los códigos de Georef (INDEC), estables entre versiones.
-- Se carga en la base para que funcione sin internet y siempre con los mismos datos (casos de prueba).

CREATE TABLE provincia (
    id      VARCHAR(2)   PRIMARY KEY,
    nombre  VARCHAR(100) NOT NULL
);

CREATE TABLE localidad (
    id            VARCHAR(10)  PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    -- Partido o departamento: distingue localidades con el mismo nombre en una provincia (ej. San José)
    departamento  VARCHAR(100) NOT NULL,
    provincia_id  VARCHAR(2)   NOT NULL REFERENCES provincia(id)
);
CREATE INDEX ix_localidad_provincia ON localidad (provincia_id);

